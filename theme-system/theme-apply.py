#!/usr/bin/env python3
"""
Apply a helix theme across helix, ghostty, zellij, and yazi/gtop (via inherited terminal palette).

Usage:
    theme-apply.py <theme-name>           # apply theme globally
    theme-apply.py --current              # print current helix theme name
    theme-apply.py --preview <theme-name> # apply globally AND print swatch preview

    theme-apply.py --local <theme-name>   # bind $PWD to a theme, repaint this terminal
    theme-apply.py --local-clear          # drop $PWD's binding, repaint this terminal
    theme-apply.py --preview-local <name> # repaint this terminal only, print swatch
    theme-apply.py --sync                 # reconcile this terminal against $PWD

    theme-apply.py --ssh <host> <name>    # bind a host to a theme
    theme-apply.py --ssh-clear <host>     # drop a host's binding
    theme-apply.py --ssh-current <host>   # print the theme bound to a host, if any
    theme-apply.py --terminal <name>      # repaint this terminal only, no swatch

Three scopes:
    global — writes the config files below and repaints every terminal.
    local  — a directory bound to a theme in the registry. Repaints only the
             calling terminal (OSC is per-surface) and generates a helix config
             variant for `hx -c`; touches no global config. Bindings are
             inherited by subdirectories, nearest ancestor wins.
    ssh    — a host bound to a theme in the same registry (under `ssh:` keys).
             The fish `ssh` wrapper paints the calling terminal before
             connecting and restores it on exit; OSC crosses the connection, so
             the remote session inherits the palette without any remote setup.

Reads:
    Helix theme files from ~/.config/helix/themes/, ~/helix-ide/config/helix/themes/,
    and /usr/lib/helix/runtime/themes/ (in that precedence order).

Writes:
    ~/.config/ghostty/theme-current.conf — ghostty palette (`config-file`d from its config)
    ~/.config/zellij/config.kdl          — managed `themes { theme-current { ... } }` block
    ~/.config/helix/config.toml          — updates `theme = "..."` (global theme = source of truth)
    ~/.config/theme-system/local.toml    — directory and `ssh:host` → theme bindings
    ~/.cache/theme-system/helix-*.toml   — per-theme helix configs for `hx -c` (local scope)

Signals:
    OSC 4/10/11/12/17/19 on every owned tty (live palette swap — see set_colors_osc)
    (zellij watches config.kdl and live-reloads the inline theme on write — no signal)
    pkill -SIGUSR1 hx                       (helix config reload, buffer-safe)
    pkill -SIGWINCH -f gtop                 (blessed full-repaint against new palette)
"""

import json
import os
import re
import shutil
import signal
import subprocess
import sys
from pathlib import Path

try:
    import tomllib  # py3.11+
except ImportError:
    try:
        import tomli as tomllib  # py3.7+, needs `pip install --user tomli`
    except ImportError:
        try:
            import toml as _toml  # py2.7+, needs `pip install --user toml`

            class tomllib:  # noqa: N801 — shim to match tomllib.load API
                @staticmethod
                def load(f):
                    data = f.read()
                    if isinstance(data, bytes):
                        data = data.decode("utf-8")
                    return _toml.loads(data)
        except ImportError:
            sys.exit(
                "error: needs python 3.11+, or `pip install --user tomli`, "
                "or `pip install --user toml`"
            )

HOME = Path.home()
SCRIPT_DIR = Path(__file__).resolve().parent
THEME_DIRS = [
    HOME / ".config/helix/themes",
    HOME / "helix-ide/config/helix/themes",
    Path("/usr/lib/helix/runtime/themes"),
    SCRIPT_DIR / "themes",
]
GHOSTTY_THEME_OUT = HOME / ".config/ghostty/theme-current.conf"
ZELLIJ_CONFIG = HOME / ".config/zellij/config.kdl"
HELIX_CONFIG = HOME / ".config/helix/config.toml"
LOCAL_REGISTRY = HOME / ".config/theme-system/local.toml"
HELIX_VARIANT_DIR = HOME / ".cache/theme-system"

# zellij has no KDL include mechanism and only live-reloads themes defined
# *inline* in the main config, so theme-apply.py owns a delimited block inside
# config.kdl (analogous to ghostty's `config-file`d theme-current.conf). The markers
# below bound the region it rewrites; everything outside them is left untouched.
ZELLIJ_THEME_NAME = "theme-current"
ZELLIJ_BLOCK_START = "// >>> theme-system (generated by theme-apply.py — do not edit) >>>"
ZELLIJ_BLOCK_END = "// <<< theme-system <<<"

# Host bindings share local.toml — same shape (key → theme name), same
# lifecycle. Prefixed so they can never collide with an absolute path key.
SSH_PREFIX = "ssh:"

HEX_RE = re.compile(r"^#[0-9a-fA-F]{6}$")


def find_theme_file(name):
    for d in THEME_DIRS:
        p = d / f"{name}.toml"
        if p.is_file():
            return p
    sys.exit(f"error: theme '{name}' not found in {[str(d) for d in THEME_DIRS]}")


def load_theme_chain(name, seen=None):
    """Load theme, following `inherits` recursively. Child overrides parent."""
    if seen is None:
        seen = set()
    if name in seen:
        sys.exit(f"error: cycle in theme inheritance at '{name}'")
    seen.add(name)

    path = find_theme_file(name)
    with open(path, "rb") as f:
        data = tomllib.load(f)

    parent_name = data.pop("inherits", None)
    if parent_name:
        parent = load_theme_chain(parent_name, seen)
        # deep-merge: child scalars/tables win; palette merged
        merged = {**parent, **data}
        merged_palette = {**parent.get("palette", {}), **data.get("palette", {})}
        if merged_palette:
            merged["palette"] = merged_palette
        return merged
    return data


def resolve_color(val, palette):
    """Resolve a theme value (str or table) into a hex color or None."""
    if val is None:
        return None
    if isinstance(val, dict):
        # try fg first (foreground colors carry more info for most keys),
        # caller chooses fg vs bg by picking the field
        return None  # caller handles dict access explicitly
    if isinstance(val, str):
        if HEX_RE.match(val):
            return val.lower()
        # named palette reference
        looked = palette.get(val)
        if looked and isinstance(looked, str) and HEX_RE.match(looked):
            return looked.lower()
    return None


def get_fg(theme, key):
    """Extract fg color from theme[key], resolving palette refs."""
    palette = theme.get("palette", {})
    val = theme.get(key)
    if isinstance(val, str):
        return resolve_color(val, palette)
    if isinstance(val, dict):
        fg = val.get("fg")
        if fg is not None:
            return resolve_color(fg, palette)
    return None


def get_bg(theme, key):
    palette = theme.get("palette", {})
    val = theme.get(key)
    if isinstance(val, dict):
        bg = val.get("bg")
        if bg is not None:
            return resolve_color(bg, palette)
    return None


def palette_lookup(palette, *names):
    for n in names:
        v = palette.get(n)
        if isinstance(v, str) and HEX_RE.match(v):
            return v.lower()
    return None


def brighten(hex_color, amount=24):
    """Lighten a hex color by adding `amount` to each channel."""
    r = min(255, int(hex_color[1:3], 16) + amount)
    g = min(255, int(hex_color[3:5], 16) + amount)
    b = min(255, int(hex_color[5:7], 16) + amount)
    return f"#{r:02x}{g:02x}{b:02x}"


def derive_palette(theme):
    """Derive the terminal palette from a helix theme."""
    p = theme.get("palette", {})

    bg = (
        get_bg(theme, "ui.background")
        or palette_lookup(p, "background", "bg", "base", "base00", "black")
        or "#1e1e2e"
    )
    fg = (
        get_fg(theme, "ui.text")
        or palette_lookup(p, "foreground", "fg", "text", "base05", "white")
        or "#cdd6f4"
    )
    cursor = (
        get_bg(theme, "ui.cursor.primary")
        or get_fg(theme, "ui.cursor")
        or fg
    )
    sel_bg = (
        get_bg(theme, "ui.selection")
        or palette_lookup(p, "selection", "surface1", "base02")
        or "#3f4258"
    )
    sel_fg = get_fg(theme, "ui.selection") or fg

    # ANSI 16 — prefer literal color names in palette, fall back to semantic roles.
    def pick(names, semantic_keys, default):
        v = palette_lookup(p, *names)
        if v:
            return v
        for k in semantic_keys:
            v = get_fg(theme, k) or get_bg(theme, k)
            if v:
                return v
        return default

    black = bg
    red = pick(
        ["red", "base08"],
        ["error", "diagnostic.error", "keyword.control.exception"],
        "#f38ba8",
    )
    green = pick(
        ["green", "base0B"],
        ["string", "diff.plus", "markup.list.checked"],
        "#a6e3a1",
    )
    yellow = pick(
        ["yellow", "base0A"],
        ["warning", "diagnostic.warning", "constant.numeric"],
        "#f9e2af",
    )
    blue = pick(
        ["blue", "base0D"],
        ["function", "info", "diagnostic.info"],
        "#89b4fa",
    )
    magenta = pick(
        ["magenta", "purple", "mauve", "pink", "base0E"],
        ["keyword", "keyword.control", "operator"],
        "#cba6f7",
    )
    cyan = pick(
        ["cyan", "teal", "sapphire", "sky", "base0C"],
        ["type", "constructor", "namespace"],
        "#94e2d5",
    )
    white = fg

    # bright variants: try named brights, else lighten
    def bright(names, base):
        v = palette_lookup(p, *names)
        return v if v else brighten(base)

    br_black = bright(["bright_black", "gray", "grey", "surface2", "base03"], black)
    br_red = bright(["bright_red"], red)
    br_green = bright(["bright_green"], green)
    br_yellow = bright(["bright_yellow"], yellow)
    br_blue = bright(["bright_blue"], blue)
    br_magenta = bright(["bright_magenta", "bright_purple"], magenta)
    br_cyan = bright(["bright_cyan"], cyan)
    br_white = bright(["bright_white"], white)

    return {
        "background": bg,
        "foreground": fg,
        "cursor": cursor,
        "selection_background": sel_bg,
        "selection_foreground": sel_fg,
        "color0": black,
        "color1": red,
        "color2": green,
        "color3": yellow,
        "color4": blue,
        "color5": magenta,
        "color6": cyan,
        "color7": white,
        "color8": br_black,
        "color9": br_red,
        "color10": br_green,
        "color11": br_yellow,
        "color12": br_blue,
        "color13": br_magenta,
        "color14": br_cyan,
        "color15": br_white,
    }


# Internal palette keys → ghostty config keys. The ANSI 16 are handled
# separately: ghostty spells them as repeated `palette = <n>=<hex>` lines
# rather than kitty's one `colorN` key each.
GHOSTTY_KEYS = {
    "background": "background",
    "foreground": "foreground",
    "cursor": "cursor-color",
    "selection_background": "selection-background",
    "selection_foreground": "selection-foreground",
}


def write_ghostty_conf(palette):
    GHOSTTY_THEME_OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# generated by theme-apply.py — do not edit\n"]
    for src, key in GHOSTTY_KEYS.items():
        lines.append(f"{key} = {palette[src]}\n")
    for i in range(16):
        lines.append(f"palette = {i}={palette[f'color{i}']}\n")
    GHOSTTY_THEME_OUT.write_text("".join(lines))


def derive_zellij_theme(palette):
    """zellij is a multiplexer, not a terminal emulator — it has no ANSI-16
    palette of its own (ghostty supplies that). Its classic theme format is just
    fg/bg + the eight base ANSI hues + `orange`; zellij derives all its own UI
    chrome (tab bar, status line, pane frames) from those. ANSI-16 has no
    dedicated orange, so map it to yellow — the nearest hue."""
    return {
        "fg": palette["foreground"],
        "bg": palette["background"],
        "black": palette["color0"],
        "red": palette["color1"],
        "green": palette["color2"],
        "yellow": palette["color3"],
        "blue": palette["color4"],
        "magenta": palette["color5"],
        "cyan": palette["color6"],
        "white": palette["color7"],
        "orange": palette["color3"],
    }


def render_zellij_block(palette):
    theme = derive_zellij_theme(palette)
    lines = [
        ZELLIJ_BLOCK_START,
        f'theme "{ZELLIJ_THEME_NAME}"',
        "themes {",
        f"    {ZELLIJ_THEME_NAME} {{",
    ]
    for k, v in theme.items():
        lines.append(f'        {k} "{v}"')
    lines += ["    }", "}", ZELLIJ_BLOCK_END]
    return "\n".join(lines) + "\n"


def _strip_managed_block(text):
    """Remove our own delimited block (markers + contents), if present."""
    pattern = re.compile(
        re.escape(ZELLIJ_BLOCK_START) + r".*?" + re.escape(ZELLIJ_BLOCK_END) + r"\n?",
        re.DOTALL,
    )
    return pattern.sub("", text)


def _strip_foreign_theme_current(text):
    """Remove any *other* `theme-current` definition that would shadow ours.

    zellij has no include mechanism, so we own an appended block (see
    ZELLIJ_BLOCK_START). The catch: opening zellij's configuration plugin — or
    anything that makes zellij re-serialize config.kdl — rewrites the file into
    its fully-materialized form, freezing the *then-current* theme into a
    `themes { theme-current { ... } }` block (in zellij's newer component
    format) near the top, plus its own top-level `theme "theme-current"` line.
    Those duplicates take precedence over our appended block, so theme switches
    silently stop affecting zellij. Strip them here so our block is the sole
    definition; a rewrite is healed by the next `theme` invocation.

    Call this *after* _strip_managed_block so our own block isn't matched.
    """
    # 1. Brace-balanced removal of any top-level `themes { ... }` block whose
    #    body mentions theme-current. Collect spans first, delete last-first so
    #    earlier indices stay valid.
    spans = []
    for m in re.finditer(r"(?m)^themes[^\S\n]*\{", text):
        depth = 0
        k = m.end() - 1  # index of the opening brace
        while k < len(text):
            c = text[k]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    break
            k += 1
        end = k + 1
        if ZELLIJ_THEME_NAME in text[m.start():end]:
            if end < len(text) and text[end] == "\n":
                end += 1
            spans.append((m.start(), end))
    for start, end in reversed(spans):
        text = text[:start] + text[end:]

    # 2. Remove stray top-level `theme "..."` directives (zellij materializes
    #    one). `\s+` after the bare word keeps `theme_dark`/`theme_light` and
    #    commented `// theme ...` lines untouched.
    text = re.sub(r'(?m)^theme[^\S\n]+"[^"]*"[^\n]*\n?', "", text)
    return text


def write_zellij_conf(palette):
    ZELLIJ_CONFIG.parent.mkdir(parents=True, exist_ok=True)
    block = render_zellij_block(palette)
    if ZELLIJ_CONFIG.is_file():
        text = ZELLIJ_CONFIG.read_text()
        text = _strip_managed_block(text)
        text = _strip_foreign_theme_current(text)
        # Re-append our block as the sole theme-current definition, leaving the
        # rest of the user's config.kdl untouched.
        text = text.rstrip("\n")
        if text:
            text += "\n"
        text += block
    else:
        text = block
    ZELLIJ_CONFIG.write_text(text)


def read_registry():
    """Directory → theme bindings. Missing or malformed file reads as empty."""
    if not LOCAL_REGISTRY.is_file():
        return {}
    with open(LOCAL_REGISTRY, "rb") as f:
        return {k: v for k, v in tomllib.load(f).items() if isinstance(v, str)}


def write_registry(reg):
    # Removed rather than left empty: fish skips its per-cd python spawn when
    # this file is absent, so unbinding the last folder restores a free cd.
    if not reg:
        LOCAL_REGISTRY.unlink(missing_ok=True)
        return
    LOCAL_REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    # json.dumps produces a valid TOML basic string for any path or theme name
    # we store, so the file stays readable by tomllib without a TOML writer dep.
    lines = ["# generated by theme-apply.py — edit with `theme --local <name>`\n"]
    lines += [f"{json.dumps(k)} = {json.dumps(v)}\n" for k, v in sorted(reg.items())]
    LOCAL_REGISTRY.write_text("".join(lines))


def resolve_local(cwd=None):
    """Theme bound to cwd or its nearest bound ancestor, else None.

    Walking upward means a binding on ~/work themes every project under it,
    and a binding deeper down overrides it.
    """
    reg = read_registry()
    if not reg:
        return None
    here = Path(cwd) if cwd else Path.cwd()
    here = here.resolve()
    for d in (here, *here.parents):
        name = reg.get(str(d))
        if name:
            return name
    return None


def _config_with_theme(text, theme_name):
    """helix config text with its `theme =` line set to theme_name."""
    new_line = f'theme = "{theme_name}"'
    if re.search(r"(?m)^\s*theme\s*=", text):
        return re.sub(r"(?m)^\s*theme\s*=.*$", new_line, text, count=1)
    return new_line + "\n" + text


def update_helix_config(theme_name):
    HELIX_CONFIG.parent.mkdir(parents=True, exist_ok=True)
    base = HELIX_CONFIG.read_text() if HELIX_CONFIG.is_file() else ""
    HELIX_CONFIG.write_text(_config_with_theme(base, theme_name))


def write_helix_variant(theme_name):
    """A copy of the global helix config with `theme` swapped, for `hx -c`.

    helix has no per-project theme and reloads only the config path it was
    started with, so a folder-local theme has to reach helix as a whole config
    file. Regenerated on every sync, so edits to the global config (keymaps,
    editor settings) are never stranded in a stale variant.
    """
    base = HELIX_CONFIG.read_text() if HELIX_CONFIG.is_file() else ""
    HELIX_VARIANT_DIR.mkdir(parents=True, exist_ok=True)
    out = HELIX_VARIANT_DIR / f"helix-{theme_name}.toml"
    out.write_text(_config_with_theme(base, theme_name))
    return out


def current_helix_theme():
    if not HELIX_CONFIG.is_file():
        return None
    m = re.search(r'(?m)^\s*theme\s*=\s*"([^"]+)"', HELIX_CONFIG.read_text())
    return m.group(1) if m else None


def owned_ttys():
    """Every tty with a process of ours on it — i.e. every open terminal.

    `ps -x` is already scoped to the current user, so this never touches
    someone else's terminal. Falls back to the controlling tty if ps is
    unavailable or reports nothing.
    """
    ttys = set()
    try:
        out = subprocess.run(
            ["ps", "-xo", "tty="], capture_output=True, text=True, check=False
        ).stdout
        ttys = {f"/dev/{t}" for t in out.split() if t not in ("??", "?", "-")}
    except OSError:
        pass
    ttys.add("/dev/tty")  # our own, in case ps missed it
    return sorted(ttys)


def set_colors_osc(palette, ttys=None):
    """Repaint every open terminal via OSC escape sequences.

    Ghostty has no remote-control CLI (kitty's `kitty @ set-colors`); its only
    config-reload trigger is the super+shift+, keybind. So the live swap goes
    out as the standard OSC color sequences instead — which the terminal
    applies instantly, needs no reload, and works verbatim over SSH (the
    cluster gets themed by the same call, rather than depending on the local
    emulator's palette leaking through).

    Broadcast to *every* tty we own, not just the controlling one: OSC is
    per-surface, so writing only to /dev/tty repaints the window `theme` ran
    in and leaves every other window on the old palette until it restarts.

    Written to ttys, never stdout: during `theme`'s fzf preview stdout is a
    pipe fzf renders into, so escapes sent there would print as literal
    garbage in the preview pane instead of reaching the terminal.

    OSC 4 = ANSI 16, 10/11/12 = fg/bg/cursor, 17/19 = selection bg/fg.
    Terminals ignore OSC codes they don't implement, so this degrades quietly.

    `ttys` narrows the broadcast — the local scope passes ["/dev/tty"] so a
    folder-bound theme repaints the calling terminal and nothing else.
    """
    esc = "".join(f"\033]4;{i};{palette[f'color{i}']}\007" for i in range(16))
    esc += f"\033]10;{palette['foreground']}\007"
    esc += f"\033]11;{palette['background']}\007"
    esc += f"\033]12;{palette['cursor']}\007"
    esc += f"\033]17;{palette['selection_background']}\007"
    esc += f"\033]19;{palette['selection_foreground']}\007"
    data = esc.encode()
    for tty in (ttys if ttys is not None else owned_ttys()):
        # O_NONBLOCK|O_NOCTTY: never block on a tty with no reader, never
        # accidentally adopt one as our controlling terminal.
        try:
            fd = os.open(tty, os.O_WRONLY | os.O_NONBLOCK | os.O_NOCTTY)
        except OSError:
            continue  # gone, busy, or not ours — skip it
        try:
            os.write(fd, data)
        except OSError:
            pass
        finally:
            os.close(fd)


# No reload_zellij(): the theme lives inline in config.kdl, which zellij watches
# and live-reloads on change, so the write in write_zellij_conf() is the signal.
# (This only holds for inline themes — themes in the themes/ folder aren't
# watched, which is why the block is embedded in the main config.)


def reload_helix():
    if not shutil.which("pkill"):
        return
    subprocess.run(["pkill", "-SIGUSR1", "-x", "hx"], check=False, capture_output=True)


def reload_gtop():
    # gtop (a blessed TUI) has no theme hot-reload, and its colors are the
    # named ANSI palette (ghostty already supplies that). The catch: blessed's
    # normal render only re-emits cells whose glyph changed, so after a live
    # palette swap a mostly-static graph keeps the colors ghostty resolved when
    # they were first drawn — it looks like the theme "didn't apply". SIGWINCH
    # makes blessed realloc + full-repaint, re-emitting every cell against
    # ghostty's now-updated palette. Same idea as reload_helix()'s SIGUSR1.
    # -f (not -x) because the process name is `node`, with gtop in its argv.
    if not shutil.which("pkill"):
        return
    subprocess.run(["pkill", "-SIGWINCH", "-f", "gtop"], check=False, capture_output=True)


def print_swatch(name, palette):
    def sw(hex_color: str) -> str:
        r, g, b = int(hex_color[1:3], 16), int(hex_color[3:5], 16), int(hex_color[5:7], 16)
        return f"\x1b[48;2;{r};{g};{b}m   \x1b[0m"

    print(f"\n  \x1b[1m{name}\x1b[0m")
    print(f"\n  bg {palette['background']}  fg {palette['foreground']}")
    print(f"  {sw(palette['background'])}{sw(palette['foreground'])}\n")
    row1 = "  " + "".join(sw(palette[f"color{i}"]) for i in range(8))
    row2 = "  " + "".join(sw(palette[f"color{i}"]) for i in range(8, 16))
    print(row1)
    print(row2)
    print()

    # sample text in the derived colors
    def fg(hex_color: str, s: str) -> str:
        r, g, b = int(hex_color[1:3], 16), int(hex_color[3:5], 16), int(hex_color[5:7], 16)
        return f"\x1b[38;2;{r};{g};{b}m{s}\x1b[0m"

    samples = [
        ("keyword", palette["color5"]),
        ("string", palette["color2"]),
        ("function", palette["color4"]),
        ("type", palette["color6"]),
        ("number", palette["color3"]),
        ("error", palette["color1"]),
    ]
    print("  " + "  ".join(fg(c, s) for s, c in samples))


def apply(name, preview=False):
    theme = load_theme_chain(name)
    palette = derive_palette(theme)
    write_ghostty_conf(palette)
    write_zellij_conf(palette)
    update_helix_config(name)
    # ponytail: a global apply repaints locally-bound terminals too. They heal
    # on their next cd (fish re-runs --sync). Filtering ttys by each shell's cwd
    # would need a pid→cwd walk; do that only if the flash actually annoys.
    set_colors_osc(palette)
    reload_helix()
    reload_gtop()
    if preview:
        print_swatch(name, palette)


def apply_terminal(name, preview=False):
    """Repaint the calling terminal only. Writes no global config."""
    palette = derive_palette(load_theme_chain(name))
    set_colors_osc(palette, ttys=["/dev/tty"])
    if preview:
        print_swatch(name, palette)


def sync():
    """Reconcile this terminal with $PWD. Called from fish on every cd.

    Prints the `hx -c` config path when the directory is locally bound and
    nothing when it isn't — the fish hx wrapper keys off exactly that.
    """
    local = resolve_local()
    name = local or current_helix_theme()
    if not name:
        return
    apply_terminal(name)
    if local:
        print(write_helix_variant(local))


def ssh_theme(host):
    return read_registry().get(SSH_PREFIX + host)


def bind_ssh(host, name):
    find_theme_file(name)  # fail before writing a binding that can't resolve
    reg = read_registry()
    reg[SSH_PREFIX + host] = name
    write_registry(reg)


def bind_local(name):
    find_theme_file(name)  # fail before writing a binding that can't resolve
    reg = read_registry()
    reg[str(Path.cwd().resolve())] = name
    write_registry(reg)


def main():
    args = sys.argv[1:]
    if not args:
        sys.exit(__doc__)
    if args[0] == "--current":
        cur = current_helix_theme()
        print(cur if cur else "")
        return
    if args[0] == "--sync":
        sync()
        return
    if args[0] == "--local-clear":
        reg = read_registry()
        reg.pop(str(Path.cwd().resolve()), None)
        write_registry(reg)
        sync()
        return
    if args[0] == "--ssh-current":
        if len(args) < 2:
            sys.exit("--ssh-current needs a host")
        print(ssh_theme(args[1]) or "")
        return
    if args[0] == "--ssh-clear":
        if len(args) < 2:
            sys.exit("--ssh-clear needs a host")
        reg = read_registry()
        reg.pop(SSH_PREFIX + args[1], None)
        write_registry(reg)
        return
    if args[0] == "--ssh":
        if len(args) < 3:
            sys.exit("--ssh needs a host and a theme name")
        bind_ssh(args[1], args[2])
        return
    if args[0] in ("--preview", "--preview-local", "--local", "--terminal"):
        if len(args) < 2:
            sys.exit(f"{args[0]} needs a theme name")
        if args[0] == "--preview":
            apply(args[1], preview=True)
        elif args[0] == "--preview-local":
            apply_terminal(args[1], preview=True)
        elif args[0] == "--terminal":
            apply_terminal(args[1])
        else:
            bind_local(args[1])
            sync()
        return
    apply(args[0])


if __name__ == "__main__":
    main()
